"""Build an update zip with only what changed since the last upload. See DEPLOY.md.

    python scripts/make_update.py

Compares this PC against what the server has (deploy/server-manifest.json, or
the two full zips from make_deploy.py the first time) and writes

  deploy/lct-trading-update-<date>.zip
      lct-trading/...   changed app files
      public_html/...   changed public files (new build/, new photos, .htaccess)

Extract it in the cPanel home directory (the folder that holds both
lct-trading/ and public_html/). Then it records the new state as the server's.
vendor/ and .env are never included: if composer.lock changed, ship the full zip.
"""

import hashlib
import json
import subprocess
import sys
import zipfile
from datetime import datetime
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from make_deploy import APP, OUT, ROOT, SKIP_APP, build, files, run  # noqa: E402

MANIFEST = OUT / "server-manifest.json"
NEVER = ("vendor/", "bootstrap/cache/", ".env")  # server-only or built there


def sha(data: bytes) -> str:
    return hashlib.sha1(data).hexdigest()


def from_full_zips() -> dict:
    """Snapshot of the first deploy, read from the two full zips."""
    seen = {}
    with zipfile.ZipFile(OUT / f"{APP}-full-deploy.zip") as z:
        for n in z.namelist():
            if not n.endswith("/"):
                seen["app/" + n.removeprefix(f"{APP}/")] = sha(z.read(n))
    with zipfile.ZipFile(OUT / f"{APP}-public_html-ready.zip") as z:
        for n in z.namelist():
            if not n.endswith("/"):
                seen["public/" + n] = sha(z.read(n))
    return seen


def current() -> dict:
    """What the server should have now: key -> (hash, source path)."""
    now = {}
    for f in files():
        if f.startswith(SKIP_APP) or f.startswith(NEVER):
            if not f.startswith("public/"):
                continue
        if f.startswith("public/"):
            if f == "public/index.php":
                continue  # public_html/index.php is generated by make_deploy.py
            now["public/" + f.removeprefix("public/")] = f
        else:
            now["app/" + f] = f
    for p in (ROOT / "public/build").rglob("*"):
        if p.is_file():
            now["public/" + p.relative_to(ROOT / "public").as_posix()] = p.relative_to(ROOT).as_posix()
    return {k: (sha((ROOT / src).read_bytes()), src) for k, src in now.items()}


def main():
    if subprocess.run(["git", "diff", "--quiet", "HEAD", "--", "composer.lock"], cwd=ROOT).returncode:
        print("composer.lock changed: vendor/ must be rebuilt. Use make_deploy.py (full zip) instead.")
        sys.exit(1)

    build()
    server = json.loads(MANIFEST.read_text()) if MANIFEST.exists() else from_full_zips()
    now = current()

    changed = sorted(k for k, (h, _) in now.items() if server.get(k) != h and not k.endswith(".env.production.example"))
    gone = sorted(k for k in server if k not in now and not k.startswith(tuple("app/" + n for n in NEVER))
                  and k not in ("public/index.php", "public/_storage-link.php", "app/.env.production.example"))

    if not changed:
        print("Nothing changed since the last upload.")
        return

    name = OUT / f"{APP}-update-{datetime.now():%Y%m%d-%H%M}.zip"
    with zipfile.ZipFile(name, "w", zipfile.ZIP_DEFLATED) as z:
        for k in changed:
            area, rel = k.split("/", 1)
            z.write(ROOT / now[k][1], f"{APP if area == 'app' else 'public_html'}/{rel}")

    for k in changed:
        server[k] = now[k][0]
    for k in gone:
        server.pop(k, None)
    MANIFEST.write_text(json.dumps(server, indent=0, sort_keys=True))

    print(f"\n{name.name}: {len(changed)} files, {name.stat().st_size / 1e6:.1f} MB")
    for k in changed:
        print("  +", k.replace("app/", f"{APP}/", 1).replace("public/", "public_html/", 1))
    if gone:
        print("\nNo longer used (safe to delete on the server, or leave):")
        for k in gone:
            print("  -", k.replace("app/", f"{APP}/", 1).replace("public/", "public_html/", 1))
    if any(k.startswith("app/database/migrations/") for k in changed):
        print("\nNew migration: run `php artisan migrate --force` after extracting.")


if __name__ == "__main__":
    main()
