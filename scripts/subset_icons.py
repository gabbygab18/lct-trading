"""Cut Boxicons down to the icons the site uses.

    python scripts/subset_icons.py

Scans resources/ and app/ for bx-*/bxs-*/bxl-* class names, then writes
  resources/fonts/boxicons-subset.woff2   only those glyphs (~5 KB, not 115 KB)
  resources/css/boxicons-subset.css       @font-face + .bx + those classes
Re-run after using a new icon (it says which names it couldn't find).
"""
import re
from pathlib import Path

from fontTools import subset

ROOT = Path(__file__).resolve().parent.parent
BOX = ROOT / "node_modules" / "boxicons"
FONT_OUT = ROOT / "resources" / "fonts" / "boxicons-subset.woff2"
CSS_OUT = ROOT / "resources" / "css" / "boxicons-subset.css"
NAME = re.compile(r"\bbx[sl]?-[a-z0-9-]+")
HELPERS = {"bx-spin", "bx-ul"}  # utility classes, not glyphs

used = set()
for d in ("resources/js", "resources/views", "resources/css", "app"):
    for f in (ROOT / d).rglob("*"):
        if f.is_file() and f.suffix in (".jsx", ".js", ".php", ".css") and f != CSS_OUT:
            used |= set(NAME.findall(f.read_text(encoding="utf-8", errors="ignore")))

css = (BOX / "css" / "boxicons.css").read_text(encoding="utf-8")
codes = dict(re.findall(r"\.(bx[sl]?-[a-z0-9-]+):before\s*\{\s*content:\s*\"\\([0-9a-f]+)\"", css))

glyphs = {n: codes[n] for n in sorted(used) if n in codes}
missing = sorted(used - set(codes) - HELPERS)

opts = subset.Options()
opts.flavor = "woff2"
opts.layout_features = []
opts.name_IDs = []
opts.notdef_outline = True
font = subset.load_font(str(BOX / "fonts" / "boxicons.ttf"), opts)
sub = subset.Subsetter(opts)
sub.populate(unicodes=[int(c, 16) for c in glyphs.values()])
sub.subset(font)
subset.save_font(font, str(FONT_OUT), opts)

rules = "\n".join(f'.{n}::before {{ content: "\\{c}"; }}' for n, c in glyphs.items())
CSS_OUT.write_text(f"""/* Generated by scripts/subset_icons.py: only the Boxicons this site uses. */
@font-face {{
    font-family: boxicons;
    font-weight: 400;
    font-style: normal;
    font-display: block;
    src: url('../fonts/boxicons-subset.woff2') format('woff2');
}}
.bx {{
    font-family: boxicons !important;
    font-weight: 400;
    font-style: normal;
    font-variant: normal;
    line-height: 1;
    display: inline-block;
    text-transform: none;
    speak: never;
    -webkit-font-smoothing: antialiased;
    -moz-osx-font-smoothing: grayscale;
}}
.bx-spin {{ animation: bx-spin 2s linear infinite; }}
@keyframes bx-spin {{ to {{ transform: rotate(359deg); }} }}
@media (prefers-reduced-motion: reduce) {{ .bx-spin {{ animation: none; }} }}
{rules}
""", encoding="utf-8")

print(f"{len(glyphs)} icons -> {FONT_OUT.name} ({FONT_OUT.stat().st_size / 1024:.1f} KB)")
if missing:
    print("not Boxicons names (ignored):", ", ".join(missing))
